#!/bin/bash
# build_p3dfft_opt.sh gcc|intel — P3DFFT 2.x rebuilt WITH optimisation and OpenMP, plus the P3DFFT solver on it.
#
# Why: the existing builds (build/build_p3dfft.sh -> /opt/p3dfft_v2 in the GCC container, planner/build_planner.sh,
# scripts/intel/build_intel_libs.sh -> /work/opt_intel/p3dfft) have FCFLAGS = "-g" (autoconf default for a
# non-gfortran compiler): nvfortran and ifx then compile the Fortran part (pack/unpack, local transposes) at -O0.
# The GCC-container build also has no --enable-pgi, so configure adds no -mp: the !$OMP directives are ignored
# (nm: 2 OpenMP symbols, Intel build: 327) and every rank runs one thread.
#
#   gcc    GCC/NVHPC container. OMPI_FC=nvfortran OMPI_CC=nvc OMPI_CXX=nvc++, autoreconf -fi,
#          configure --enable-pgi --enable-fftw --with-fftw=/opt/fftw3 --enable-openmp,
#          FCFLAGS = CFLAGS = "-O3 -tp=zen2 -mp"; LIBS/CPPFLAGS as build/build_p3dfft.sh.
#          Solver as scripts/compile_all.sh (OMPI_CXX=nvc++ mpicxx -O3 -std=c++17 -mp).
#   intel  Intel container. As scripts/intel/build_intel_libs.sh (--enable-intel, FC=mpiifx, configure generated
#          in the GCC container by scripts/intel/prep_p3dfft_gcc.sh), FCFLAGS = CFLAGS = "-O3 -march=core-avx2"
#          (configure adds -qopenmp). NOT -xHost / -xCORE-AVX2: those binaries refuse to run on AMD.
#          Solver as scripts/intel/build_intel_solvers.sh.
#   gnu    off-cluster test only: gfortran + Open MPI wrappers, --enable-gnu, FCFLAGS = CFLAGS = "-O3 -fallow-argument-mismatch".
#
# Output (existing libraries are not touched):
#   /work/opt_p3d/<mode>                 P3DFFT (lib/libp3dfft.a, include/)
#   /work/build/bin_p3d/<mode>/ns_p3dfft solver; prints "P3DFFT library: <path> (<compiler, FCFLAGS, OpenMP symbols>)"
#   logs: /work/opt_p3d/logs/<mode>_*.log
# Checks (FAIL otherwise): FCFLAGS in build/Makefile contains -O3; nm libp3dfft.a has > $P3O_MIN_OMP (20)
#   OpenMP symbols (__kmpc|_mp_|omp_); config.h has MEASURE and OPENMP, no STRIDE1.
#
#   source ~/guohaojie/src/NavierStockes-3D/scripts/intel/intel_common.sh      # $M, $MI, $EXCL
#   srun -p batch --exclude=$EXCL -N1 -n1 -c16 --gres=gpu:1 --time=00:40:00 $M  bash /work/src/NavierStockes-3D/scripts/p3dfft/build_p3dfft_opt.sh gcc
#   srun -p batch --exclude=$EXCL -N1 -n1 -c16 --time=00:40:00 $MI bash /work/src/NavierStockes-3D/scripts/p3dfft/build_p3dfft_opt.sh intel
# Only the solver again (library already built): P3O_SOLVER_ONLY=1.
# Paths can be overridden (that is how this was tested off-cluster): P3O_ROOT (/work), P3O_FFTW, NS_SRC, P3O_PSRC.
MODE=${1:?usage: build_p3dfft_opt.sh gcc|intel}
HERE=$(cd "$(dirname "$0")" && pwd)
R=${P3O_ROOT:-/work}
MINOMP=${P3O_MIN_OMP:-20}
J=${J:-16}
case $MODE in
gcc)
    source /etc/profile.d/ns3d_env.sh
    FFTWD=${P3O_FFTW:-/opt/fftw3}
    export OMPI_FC=nvfortran OMPI_CC=nvc OMPI_CXX=nvc++
    CONF="--enable-pgi"; OPTF="-O3 -tp=zen2 -mp"; FCW=mpif90 ;;
intel)
    source "$HERE/../intel/intel_env.sh"
    FFTWD=${P3O_FFTW:-$IFFTW}
    CONF="--enable-intel"; OPTF="-O3 -march=core-avx2"
    if command -v mpiifx >/dev/null 2>&1; then FCW=mpiifx; else FCW=mpif90; fi ;;
gnu)
    FFTWD=${P3O_FFTW:?gnu mode: set P3O_FFTW to an FFTW with fftw3, fftw3f, fftw3_mpi, fftw3_threads}
    export OMPI_FC=gfortran OMPI_CC=gcc OMPI_CXX=g++
    CONF="--enable-gnu"; OPTF="-O3 -fallow-argument-mismatch"; FCW=mpif90 ;;   # gfortran >= 10 rejects P3DFFT r2c calls otherwise
*) echo "usage: build_p3dfft_opt.sh gcc|intel"; exit 2 ;;
esac
SRC=${NS_SRC:-$R/src/NavierStockes-3D}
OPT=$R/opt_p3d/$MODE; BIN=$R/build/bin_p3d/$MODE; WRK=$R/src/p3d_opt; LOGDIR=$R/opt_p3d/logs
mkdir -p $R/opt_p3d $BIN $WRK $LOGDIR
c(){ local name=$1; shift; if "$@" > $LOGDIR/${MODE}_$name.log 2>&1; then echo "OK   ${MODE}_$name"; else echo "FAIL ${MODE}_$name (see $LOGDIR/${MODE}_$name.log)"; return 1; fi; }
echo "mode=$MODE  FC=$FCW -> $($FCW -show 2>/dev/null | awk '{print $1}')  CC=mpicc -> $(mpicc -show 2>/dev/null | awk '{print $1}')  FFTW=$FFTWD"
echo "library -> $OPT   solver -> $BIN/ns_p3dfft   flags: $OPTF"

# ---------------------------------------------------------------- library
build_lib() {
    (
    set -e
    local psrc
    if [ $MODE = intel ]; then
        # the Intel container has no autoreconf: configure generated by prep_p3dfft_gcc.sh (or by a gcc run of this script)
        psrc=${P3O_PSRC:-}
        for d in $R/src/intel_libs/p3dfft $WRK/p3dfft; do [ -z "$psrc" ] && [ -x $d/configure ] && psrc=$d; done
        [ -n "$psrc" ] || { echo "ERROR: no generated configure; run scripts/intel/prep_p3dfft_gcc.sh in the GCC container first"; exit 1; }
    else
        psrc=${P3O_PSRC:-$WRK/p3dfft}
        if [ ! -d $psrc ]; then   # a local clone made by the earlier build scripts, else GitHub
            local d from=https://github.com/sdsc/p3dfft.git
            for d in $R/src/planner_libs/p3dfft $R/src/intel_libs/p3dfft; do [ -d $d/.git ] && { from=$d; break; }; done
            echo "git clone $from"; git clone -q --depth 1 file://$from $psrc 2>/dev/null || git clone -q --depth 1 $from $psrc
        fi
        # autoreconf in the source tree (not in the build copy), so an intel run can use the generated configure too
        (cd $psrc && autoreconf -fi)
    fi
    echo "P3DFFT source: $psrc  commit $(git -C $psrc log -1 --format='%h %cd' 2>/dev/null)"
    rm -rf $WRK/p3dfft_$MODE $OPT
    cp -a $psrc $WRK/p3dfft_$MODE && cd $WRK/p3dfft_$MODE
    [ -f Makefile ] && make distclean >/dev/null 2>&1 || true
    # LIBS / CPPFLAGS as build/build_p3dfft.sh
    local libs="-L$FFTWD/lib -lfftw3 -lfftw3f -lfftw3_mpi"
    echo "./configure --prefix=$OPT $CONF --enable-fftw --with-fftw=$FFTWD --enable-openmp FC=$FCW F77=$FCW CC=mpicc CXX=mpicxx FCFLAGS=\"$OPTF\" CFLAGS=\"$OPTF\" LIBS=\"$libs\" CPPFLAGS=\"-I$FFTWD/include\""
    ./configure --prefix=$OPT $CONF --enable-fftw --with-fftw=$FFTWD --enable-openmp \
        FC=$FCW F77=$FCW CC=mpicc CXX=mpicxx FCFLAGS="$OPTF" CFLAGS="$OPTF" \
        LIBS="$libs" CPPFLAGS="-I$FFTWD/include"
    grep -E "define (INTEL|PGI|GNU|OPENMP|FFTW|ESTIMATE|MEASURE|PATIENT|STRIDE1) " config.h || true
    grep -q "define MEASURE 1" config.h || { echo "ERROR: MEASURE not defined"; exit 1; }
    grep -q "define OPENMP 1" config.h  || { echo "ERROR: OPENMP not defined"; exit 1; }
    ! grep -q "define STRIDE1 1" config.h || { echo "ERROR: STRIDE1 defined"; exit 1; }
    make -j1 -C build
    make -C build install
    mkdir -p $OPT/include; cp include/*.h $OPT/include/; cp build/*.mod $OPT/include/ 2>/dev/null || true
    cp build/Makefile $OPT/Makefile.build      # kept for the flag check below and for later reference
    ls -l $OPT/lib
    )
}
if [ -z "$P3O_SOLVER_ONLY" ]; then
    c lib build_lib || { tail -20 $LOGDIR/${MODE}_lib.log; exit 1; }
fi

# ---------------------------------------------------------------- flag / OpenMP check
[ -f $OPT/Makefile.build ] && [ -f $OPT/lib/libp3dfft.a ] || { echo "FAIL ${MODE}_check: $OPT/lib/libp3dfft.a or $OPT/Makefile.build missing"; exit 1; }
echo "--- build/Makefile:"
grep -E "^(FC|FCFLAGS|FDFLAGS|CFLAGS) =" $OPT/Makefile.build
FCFL=$(awk -F' = ' '$1 == "FCFLAGS" {print $2}' $OPT/Makefile.build)
FCC=$(awk -F' = ' '$1 == "FC" {print $2}' $OPT/Makefile.build)
NOMP=$(nm $OPT/lib/libp3dfft.a 2>/dev/null | grep -ciE "__kmpc|_mp_|omp_")
echo "OpenMP symbols in libp3dfft.a (nm | grep -ciE \"__kmpc|_mp_|omp_\"): $NOMP"
ST=OK
[[ " $FCFL " == *" -O3 "* ]] || { echo "  FCFLAGS has no -O3"; ST=FAIL; }
[ "$NOMP" -gt "$MINOMP" ] || { echo "  only $NOMP OpenMP symbols (need > $MINOMP)"; ST=FAIL; }
echo "$ST  ${MODE}_check  (FCFLAGS='$FCFL', OpenMP symbols $NOMP)"
[ $ST = OK ] || exit 1

# ---------------------------------------------------------------- solver
cd $SRC || exit 1
LIBINFO="$OPT/lib/libp3dfft.a ($MODE: FC=$FCC -> $($FCW -show 2>/dev/null | awk '{print $1}'), FCFLAGS=$FCFL, OpenMP symbols $NOMP)"
PLAN='-DNS_P3DFFT_PLAN="FFTW_MEASURE"'
DLIB="-DNS_P3DFFT_LIB=\"$LIBINFO\""
P3LIBS="-lp3dfft -lfftw3_mpi -lfftw3_threads -lfftw3 -lfftw3f -lm"
RPF="-Wl,-rpath,$FFTWD/lib"
rm -f $BIN/ns_p3dfft
case $MODE in
gcc)   # scripts/compile_all.sh: nvc++ (no -fno-math-errno), Fortran runtime -lnvf, Open MPI Fortran bindings -lmpi_mpifh
    c solver env OMPI_CXX=nvc++ mpicxx -O3 -std=c++17 -mp "$PLAN" "$DLIB" NavierStokes_periodic_p3dfft.cpp \
        -I$OPT/include -I$FFTWD/include -L$OPT/lib -L$FFTWD/lib $P3LIBS -lnvf -lmpi_mpifh $RPF -o $BIN/ns_p3dfft ;;
intel) # scripts/intel/build_intel_solvers.sh: icpx links with the ifx runtime; 2nd try: mpiifx -nofor-main links
    FP=${NS_ICPX_FP--fp-model=precise}
    CXXF="-O3 -std=c++17 -fopenmp -fno-math-errno $FP"
    FORTLIB=$(dirname "$(dirname "$(command -v ifx 2>/dev/null || echo /x/x)")")/lib
    c solver mpicxx $CXXF "$PLAN" "$DLIB" NavierStokes_periodic_p3dfft.cpp -I$OPT/include -I$FFTWD/include -L$OPT/lib -L$FFTWD/lib \
        $P3LIBS -lmpifort -L$FORTLIB -lifcoremt -lifport -limf -lsvml -lintlc $RPF -Wl,-rpath,$FORTLIB -o $BIN/ns_p3dfft \
    || { echo "     retry: compile with mpicxx, link with mpiifx -nofor-main"
         c solver_obj mpicxx $CXXF "$PLAN" "$DLIB" -c NavierStokes_periodic_p3dfft.cpp -I$OPT/include -I$FFTWD/include -o $BIN/ns_p3dfft.o &&
         c solver mpiifx -nofor-main -qopenmp $BIN/ns_p3dfft.o -L$OPT/lib -L$FFTWD/lib $P3LIBS -lstdc++ $RPF -o $BIN/ns_p3dfft; } ;;
gnu)   # off-cluster test: g++ + gfortran runtime, Open MPI Fortran bindings
    c solver mpicxx -O3 -std=c++17 -fopenmp -fno-math-errno "$PLAN" "$DLIB" NavierStokes_periodic_p3dfft.cpp \
        -I$OPT/include -I$FFTWD/include -L$OPT/lib -L$FFTWD/lib $P3LIBS -lgfortran -lmpi_mpifh $RPF -o $BIN/ns_p3dfft ;;
esac
[ -x $BIN/ns_p3dfft ] || exit 1
echo "--- $BIN/ns_p3dfft: $(ls -l --time-style=+%F_%R $BIN/ns_p3dfft | awk '{print $6}')"
echo "    P3DFFT library: $LIBINFO"
ldd $BIN/ns_p3dfft | grep -E "omp|nvf|ifcore|fftw3\." | sed 's/^/    /'
